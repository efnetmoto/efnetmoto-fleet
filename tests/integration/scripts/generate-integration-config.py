#!/usr/bin/env python3
"""Generate the gitignored override files the integration tests render and start from.

  - ansible/host_vars/localhost/overrides.yml   (Ansible vars)
  - bots/<bot>/docker-compose.override.yml      (per-bot compose overrides)

The Ansible overrides point the bots at the test ircd and the api-stub and supply
dummy secrets. The compose overrides attach each bot to the external 'integration'
network and drop the published DCC ports, which would collide (Pompone and Decisis
both use 2020).

Run from the repo root: python3 tests/integration/scripts/generate-integration-config.py
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
API_STUB = "http://api-stub:8080"

# Images the CI workflow builds and tags; `compose up --no-build` then reuses them.
EGGDROP_IMAGE = "efnetmoto/eggdrop:integration"
SHORTENER_IMAGE = "efnetmoto/url-shortener:integration"

# (directory under bots/, compose service name); they differ in case.
BOTS = (("Pompone", "pompone"), ("Xerokewl", "xerokewl"), ("Decisis", "decisis"))

# Keys must match the bot's environment_variables entries so they replace them in .env.
PROVIDER_URL_OVERRIDES: dict[str, dict[str, str]] = {
    "pompone": {
        "brave_api_url": f"{API_STUB}/res/v1/web/search",
    },
    "xerokewl": {
        "weatherapi_base_url": f"{API_STUB}/v1",
        "avwx_api_url": f"{API_STUB}/api/data/metar",
        "aprsfi_api_url": f"{API_STUB}/api/get",
        "ambient_api_url": f"{API_STUB}/devices",
    },
}


def overrides_yaml() -> str:
    lines = [
        "---",
        "# Generated by tests/integration/scripts/generate-integration-config.py — DO NOT EDIT.",
        "# Local integration overrides (highest Ansible var precedence). Mirrors the",
        "# deploy playbooks' include_vars overrides.yml mechanism (gitignored).",
        "",
        "# Point bots at the test ircd (docker-DNS host 'ircd' on integration).",
        "irc_servers:",
        "  - host: ircd",
        "    port: 6667",
        "",
        "# nat-ip advertised to IRC; irrelevant on the isolated integration net but the",
        "# template requires the var (overrides the all.yml host-fact default).",
        'nat_ip: "127.0.0.1"',
        "",
        "# Dummy vault keys (non-empty satisfies provider _require_env at load).",
        "# Real secrets never enter the test path; these are throwaway values.",
        'vault_brave_api_key: "integration-brave-key"',
        'vault_shortener_api_key: "integration-shortener-key"',
        'vault_weatherapi_key: "integration-weatherapi-key"',
        'vault_aprsfi_key: "integration-aprsfi-key"',
        "",
        "# Provider URL overrides -> api-stub. render.yml merges these into each",
        "# bot's environment_variables (combine on the matching key) before .env.",
        "integration_provider_url_overrides:",
    ]
    for bot, d in PROVIDER_URL_OVERRIDES.items():
        lines.append(f"  {bot}:")
        for k, v in d.items():
            lines.append(f"    {k}: {v!r}")
    return "\n".join(lines) + "\n"


def compose_override(bot: str, bootstrap: bool = False) -> str:
    net = f"{bot}-net"
    header = (
        "# Generated by tests/integration/scripts/generate-integration-config.py — DO NOT EDIT.\n"
        f"# Attaches the {bot} service to the external integration network (so it can\n"
        "# reach the ircd, api-stub, and peer bots) and drops host-published DCC\n"
        "# ports (bots link via docker DNS on integration; host ports would collide).\n"
    )
    # --bootstrap starts the bots as `eggdrop -ntm`, which is needed once to mint the
    # userfile (see fixtures/README.md). Normally the stock entrypoint runs.
    bootstrap_block = ""
    if bootstrap:
        # Run as the runtime uid so the normal non-root boot can write the minted
        # userfile. Compose interpolates ${UID}/${GID} from .env; the inner sh -c
        # argument is single-quoted so nothing else gets interpolated.
        cmd = (
            "chown -R ${UID}:${GID} /eggdrop; "
            "exec su-exec ${UID}:${GID} /bin/sh -c "
            "'. /eggdrop/.venv/bin/activate && cd /eggdrop && "
            "exec ./eggdrop -ntm data/eggdrop.conf'"
        )
        bootstrap_block = (
            "    # bootstrap: boot eggdrop -ntm as the runtime uid (userfile creation).\n"
            '    entrypoint: ["/bin/sh", "-c"]\n'
            f'    command: ["{cmd}"]\n'
        )
    sidecars = ""
    if bot == "pompone":
        sidecars = f"  url-shortener:\n    image: {SHORTENER_IMAGE}\n"
    return (
        header
        + "services:\n"
        + f"  {bot}:\n"
        + f"    image: {EGGDROP_IMAGE}\n"
        + bootstrap_block
        + "    networks:\n"
        + "      - integration\n"
        + f"      - {net}\n"
        + "    ports: !reset []\n"
        + sidecars
        + "networks:\n"
        + "  integration:\n"
        + "    external: true\n"
    )


def main() -> int:
    import argparse

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--bootstrap",
        action="store_true",
        help=(
            "emit the compose override in userfile-creation mode: override the "
            "service entrypoint/command to boot `eggdrop -ntm` as the runtime uid. "
            "Used only when regenerating the userfile fixtures; the normal "
            "(no flag) override is what CI runs."
        ),
    )
    args = parser.parse_args()

    overrides_path = REPO / "ansible/host_vars/localhost/overrides.yml"
    overrides_path.write_text(overrides_yaml())
    print(f"wrote {overrides_path.relative_to(REPO)}")

    for dir_name, bot in BOTS:
        p = REPO / f"bots/{dir_name}/docker-compose.override.yml"
        p.write_text(compose_override(bot, bootstrap=args.bootstrap))
        print(f"wrote {p.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
